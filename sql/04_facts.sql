-- 04_facts.sql : 3 tabel fakta berbagi dimensi yang sama (galaxy schema / fact constellation)

-- =====================================================================
-- FAKTA 1 : fact_order
-- Grain  : 1 baris = 1 order (order_id)
-- Tipe   : transaction fact
-- =====================================================================
CREATE TABLE IF NOT EXISTS dw.fact_order (
    order_key          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           TEXT NOT NULL UNIQUE,                   -- degenerate dimension
    date_key           INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    time_key           INTEGER NOT NULL REFERENCES dw.dim_time(time_key),
    event_key          INTEGER NOT NULL REFERENCES dw.dim_event(event_key),
    location_key       INTEGER NOT NULL REFERENCES dw.dim_location(location_key),
    payment_key        INTEGER NOT NULL REFERENCES dw.dim_payment(payment_key),
    shipping_key       INTEGER NOT NULL REFERENCES dw.dim_shipping(shipping_key),
    status_key         INTEGER NOT NULL REFERENCES dw.dim_status(status_key),
    cancel_reason_key  INTEGER NOT NULL REFERENCES dw.dim_cancel_reason(cancel_reason_key),
    -- ukuran aditif
    total_qty          INTEGER NOT NULL CHECK (total_qty >= 0),
    total_weight_gr    INTEGER NOT NULL CHECK (total_weight_gr >= 0),
    total_returned_qty INTEGER NOT NULL CHECK (total_returned_qty >= 0),
    total_diskon       NUMERIC(14,2) NOT NULL,
    ongkir_pembeli     NUMERIC(14,2) NOT NULL,
    est_potongan_ongkir NUMERIC(14,2) NOT NULL,
    total_pembayaran   NUMERIC(14,2) NOT NULL,                 -- Rp0 pada order batal
    perkiraan_ongkir   NUMERIC(14,2) NOT NULL,
    num_categories     SMALLINT NOT NULL,
    -- ukuran estimasi (BUKAN kerugian aktual)
    est_revenue_hilang NUMERIC(14,2) NOT NULL DEFAULT 0,
    -- flag
    is_cancelled       BOOLEAN NOT NULL,
    is_returned        BOOLEAN NOT NULL,
    is_problem_order   BOOLEAN NOT NULL,
    is_time_missing    BOOLEAN NOT NULL,
    is_weight_outlier  BOOLEAN NOT NULL,                       -- > 20 kg, ditandai bukan dihapus
    -- audit trail / lineage
    order_month        DATE NOT NULL,                          -- dari waktu order, atau source_file bila kosong
    source_file        TEXT NOT NULL,
    batch_id           BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    loaded_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fo_date    ON dw.fact_order(date_key);
CREATE INDEX IF NOT EXISTS ix_fo_month   ON dw.fact_order(order_month);
CREATE INDEX IF NOT EXISTS ix_fo_status  ON dw.fact_order(status_key);
CREATE INDEX IF NOT EXISTS ix_fo_payment ON dw.fact_order(payment_key);
CREATE INDEX IF NOT EXISTS ix_fo_reason  ON dw.fact_order(cancel_reason_key);

-- =====================================================================
-- FAKTA 2 : fact_order_category
-- Grain  : 1 baris = 1 order x 1 kategori produk
-- Tipe   : transaction fact (menggantikan bridge table)
-- Catatan: weight_factor = 1 / jumlah kategori pada order, sehingga
--          SUM(weight_factor) per order = 1 dan tidak terhitung ganda
-- =====================================================================
CREATE TABLE IF NOT EXISTS dw.fact_order_category (
    order_key            BIGINT   NOT NULL REFERENCES dw.fact_order(order_key) ON DELETE CASCADE,
    category_key         INTEGER  NOT NULL REFERENCES dw.dim_product_category(category_key),
    date_key             INTEGER  NOT NULL REFERENCES dw.dim_date(date_key),
    event_key            INTEGER  NOT NULL REFERENCES dw.dim_event(event_key),
    location_key         INTEGER  NOT NULL REFERENCES dw.dim_location(location_key),
    payment_key          INTEGER  NOT NULL REFERENCES dw.dim_payment(payment_key),
    status_key           INTEGER  NOT NULL REFERENCES dw.dim_status(status_key),
    cancel_reason_key    INTEGER  NOT NULL REFERENCES dw.dim_cancel_reason(cancel_reason_key),
    weight_factor        NUMERIC(8,6) NOT NULL CHECK (weight_factor > 0 AND weight_factor <= 1),
    allocated_orders     NUMERIC(8,6) NOT NULL,                 -- = weight_factor
    allocated_payment    NUMERIC(14,2) NOT NULL,
    allocated_est_hilang NUMERIC(14,2) NOT NULL DEFAULT 0,
    is_cancelled         BOOLEAN NOT NULL,
    order_month          DATE NOT NULL,
    batch_id             BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    PRIMARY KEY (order_key, category_key)
);
CREATE INDEX IF NOT EXISTS ix_foc_category ON dw.fact_order_category(category_key);
CREATE INDEX IF NOT EXISTS ix_foc_month    ON dw.fact_order_category(order_month);

-- =====================================================================
-- FAKTA 3 : fact_daily_cancel_snapshot
-- Grain  : 1 baris = 1 tanggal x 1 metode bayar x 1 layanan kirim
--          (order tanpa tanggal: date_key = -1, dibedakan oleh order_month)
-- Tipe   : periodic snapshot, dibentuk ulang dari fact_order tiap batch
-- =====================================================================
CREATE TABLE IF NOT EXISTS dw.fact_daily_cancel_snapshot (
    snapshot_key       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key           INTEGER NOT NULL REFERENCES dw.dim_date(date_key),
    event_key          INTEGER NOT NULL REFERENCES dw.dim_event(event_key),
    payment_key        INTEGER NOT NULL REFERENCES dw.dim_payment(payment_key),
    shipping_key       INTEGER NOT NULL REFERENCES dw.dim_shipping(shipping_key),
    order_month        DATE    NOT NULL,
    total_orders       INTEGER NOT NULL,
    cancelled_orders   INTEGER NOT NULL,
    returned_orders    INTEGER NOT NULL,
    realized_payment   NUMERIC(16,2) NOT NULL,
    est_revenue_hilang NUMERIC(16,2) NOT NULL,
    batch_id           BIGINT NOT NULL REFERENCES etl.etl_batch(batch_id),
    UNIQUE (date_key, order_month, payment_key, shipping_key),
    CHECK (cancelled_orders <= total_orders)
);
CREATE INDEX IF NOT EXISTS ix_fdcs_month ON dw.fact_daily_cancel_snapshot(order_month);
