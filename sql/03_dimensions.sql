-- 03_dimensions.sql : 9 conformed dimension (dipakai bersama oleh 3 tabel fakta)
-- Konvensi: key -1 = Unknown (data tidak tersedia / tidak terpetakan)

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key       INTEGER PRIMARY KEY,                -- yyyymmdd ; -1 = Unknown
    full_date      DATE,
    day_of_month   SMALLINT,
    day_name       TEXT,
    iso_week       SMALLINT,
    month_num      SMALLINT,
    month_name     TEXT,
    month_start    DATE,
    quarter_num    SMALLINT,
    year_num       SMALLINT,
    is_weekend     BOOLEAN,
    is_twin_date   BOOLEAN,                            -- tanggal kembar 1.1 ... 12.12
    is_holiday     BOOLEAN,
    holiday_name   TEXT,
    is_payday      BOOLEAN                             -- periode gajian (tgl 25 s.d. 3) -- aturan di docs/
);

CREATE TABLE IF NOT EXISTS dw.dim_time (
    time_key    INTEGER PRIMARY KEY,                   -- hhmm ; -1 = Unknown
    hour_24     SMALLINT,
    minute_num  SMALLINT,
    day_part    TEXT                                   -- Dini Hari|Pagi|Siang|Sore|Malam
);

CREATE TABLE IF NOT EXISTS dw.dim_event (
    event_key      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name     TEXT NOT NULL,                      -- 'Hari Biasa' (0) | 'Unknown' (-1) | nama event
    event_category TEXT NOT NULL,                      -- Tanggal Kembar|Harbolnas|Libur|Lebaran|Biasa
    start_date     DATE,
    end_date       DATE
);

CREATE TABLE IF NOT EXISTS dw.dim_location (
    location_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name     TEXT NOT NULL,
    region_type   TEXT,                                -- Kota | Kabupaten
    province_name TEXT NOT NULL,
    island        TEXT,
    bps_code      TEXT,
    UNIQUE (province_name, city_name)
);

CREATE TABLE IF NOT EXISTS dw.dim_payment (
    payment_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_name  TEXT NOT NULL UNIQUE,
    payment_group TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_shipping (
    shipping_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier       TEXT NOT NULL,                       -- 'Tidak Tercatat' untuk Hemat Kargo tanpa kurir
    service_name  TEXT NOT NULL,
    service_class TEXT NOT NULL,
    UNIQUE (courier, service_name)
);

-- SCD Type 1 (menimpa); status order berubah setelah dimuat, riwayat tidak disimpan
CREATE TABLE IF NOT EXISTS dw.dim_status (
    status_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name TEXT NOT NULL UNIQUE,                  -- Selesai|Batal|Sedang Dikirim|Telah Dikirim|Masa Retur
    is_final    BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_cancel_reason (
    cancel_reason_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor             TEXT NOT NULL,                   -- Pembeli|Sistem|Penjual|Tidak Ada
    reason_std        TEXT NOT NULL,
    reason_group      TEXT NOT NULL,
    is_preventable    BOOLEAN NOT NULL,
    UNIQUE (actor, reason_std)
);

CREATE TABLE IF NOT EXISTS dw.dim_product_category (
    category_key   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name  TEXT NOT NULL UNIQUE,
    category_group TEXT
);

